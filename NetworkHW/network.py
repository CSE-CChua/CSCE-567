import pandas as pd
from d3graph import d3graph, vec2adjmat

# Load specific sheet from Excel file
# Load nodes (Sheet 1)
df_nodes = pd.read_excel("NetworkHW/Network_HW_Data.xlsx", sheet_name="primary characters")

# Load edges (Sheet 2)
df_edges = pd.read_excel("NetworkHW/Network_HW_Data.xlsx", sheet_name="conversational lines")


# Rename columns to match d3graph's expected format
df_edges = df_edges.rename(columns={
    "speaking character": "source",
    "character spoken to": "target",
    "number of lines spoken directly to": "weight"
    })

# save the cleaned data to a new CSV file
df_edges.to_csv("NetworkHW/network.csv", index=False)

# Convert the 3-column edge list into the square adjacency matrix format
adjmatrix = vec2adjmat(df_edges['source'], df_edges['target'], weight=df_edges['weight'])

# Initialize the graph
d3 = d3graph()

# Initialize the graph with the adjacency matrix
d3.graph(adjmatrix)


# Apply Node Properties
# Create dictionary linking character names to their line counts
size_dict = dict(zip(df_nodes['name'], df_nodes['total number of lines']))

# Extract the order of nodes generated by d3graph
node_names = d3.adjmat.columns

# Build a list of sizes tha matches this exact order
ordered_sizes = [size_dict.get(name, 10) * 3 for name in node_names]

# Build a list for colors
ordered_colors = list(node_names)
                 
# Apply dictionaries to the graph
d3.set_node_properties(
    size = ordered_sizes,
    color = ordered_colors
)

# Generate and open the graph in a web browser
d3.show(filepath="NetworkHW/network.html")